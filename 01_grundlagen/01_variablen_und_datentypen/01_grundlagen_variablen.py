# [WAS IST EINE VARIABLE UND EIN WERT?]
# Eine Variable ist wie eine beschriftete Schachtel im Computerspeicher.
# 
# Syntax:
# variablen_name = wert
# 
# - Links:  Der Name der Schachtel (z. B. vorname, alter, preis)
# - Mitte:  Das '=' Zeichen (bedeutet: 'speichere den Wert in die Schachtel')
# - Rechts: Der Wert, den du hineinlegst

# ==============================================================================
# [DIE 4 ARTEN VON WERTEN (DATENTYPEN)]
# ==============================================================================

# 1. Text (String): Immer in Anfuehrungszeichen "..." schreiben!
#    (Ohne Anfuehrungszeichen wuerde Python denken, es waere ein Variablenname.)
name = "Alex"

# 2. Ganze Zahl (Integer): Reine Zahl, OHNE Komma, OHNE Anfuehrungszeichen
alter = 28

# 3. Kommazahl (Float): Dezimalzahl, ACHTUNG: immer mit Punkt (.) statt Komma (,)
preis = 4.99

# 4. Wahrheitswert (Boolean): Nur zwei feste Zustaende: True oder False
ist_aktiv = True


# ==============================================================================
# [WERTE ANZEIGEN MIT print()]
# Mit print(variable) kannst du nachsehen, was in der Schachtel liegt:
# ==============================================================================

print(name)
print(alter)
print(preis)
print(ist_aktiv)

print("=" * 60)


# ==============================================================================
# 💡 WICHTIGER TIPP FUER ANFAENGER:
# Zeilen, die mit einer Raute (#) beginnen, sind nur "Kommentare" (Erklaerungen).
# Python ignoriert alles hinter einer Raute vollstaendig!
#
# 👉 Wo tippst du deinen Code ein?
# Schreibe deine Loesung immer in die LEERE ZEILE DARUNTER!
# Setze vor deinen eigenen Code NIEMALS eine Raute (#),
# sonst wird deine Loesung von Python nicht ausgefuehrt!
# ==============================================================================


